class DocumentStore:
    """Live TF-IDF store. Documents can be added at runtime (store_memory)."""

    def __init__(self, docs: list[dict]):
        self.docs = list(docs)
        self._rebuild()

    def _rebuild(self):
        texts = [d["content"] for d in self.docs]
        if not texts:
            self._vectorizer = None
            self._matrix = None
            return
        self._vectorizer = TfidfVectorizer(stop_words="english", ngram_range=(1, 2))
        self._matrix = self._vectorizer.fit_transform(texts)

    def add(self, doc: dict):
        self.docs.append(doc)
        self._rebuild()

    def query(self, query: str, top_k: int = 3) -> list[dict]:
        if self._vectorizer is None:
            return []
        q_vec = self._vectorizer.transform([query])
        scores = cosine_similarity(q_vec, self._matrix)[0]
        ranked = sorted(enumerate(scores), key=lambda x: x[1], reverse=True)[:top_k]
        return [
            {**self.docs[i], "relevance_score": round(float(s), 4)}
            for i, s in ranked
            if s > 0
        ]

    def coverage_audit(self, queries: list[str]) -> None:
        """Show retrieval rank of poison doc across multiple query patterns."""
        poison_id = "doc_dhp118_injected"
        print(f"\n  {'Query':<45} {'Poison rank':<12} {'Score'}")
        print(f"  {'-'*70}")
        for q in queries:
            hits = self.query(q, top_k=len(self.docs))
            ids = [h["id"] for h in hits]
            score = next((h["relevance_score"] for h in hits if h["id"] == poison_id), 0.0)
            rank = ids.index(poison_id) + 1 if poison_id in ids else "—"
            in_top3 = "✓" if isinstance(rank, int) and rank <= 3 else " "
            print(f"  {in_top3} {q:<44} #{rank:<11} {score:.4f}")


